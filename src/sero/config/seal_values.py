"""Turn a rendered seal stanza into a Helm values overlay (D2a).

``sero.config.seal`` renders the seal stanza. Something has to put it where
OpenBao reads it, and with the pinned chart that place is one Helm value:
``server.ha.raft.config``, the whole server config as a literal block. A chart
value is replaced, not merged, so an overlay that carries the seal stanza has to
carry the rest of the server config with it. This module takes the raft HCL the
deployment already runs, inserts the stanza into it, and returns the overlay to
layer after the base and environment values files.

Two rules the live migration taught:

* The stanza goes *before* ``service_registration``, which is conventionally the
  last block in these configs, so the emitted file reads like the hand-written
  one it replaces. With no such line, the stanza is appended.
* The identity that reaches the cloud KMS is the vault pod's service account, so
  the same overlay carries the annotations that bind it (workload identity on
  GKE, an IRSA role annotation on EKS). They are passed in rather than derived:
  which annotation binds an identity is the cluster's convention, not Sero's.

Pure: it takes strings and returns a string. Reading the files and printing the
result is the CLI's job.
"""

from __future__ import annotations

import yaml

from sero.config.seal import SHAMIR, SealConfig
from sero.config.teams import ConfigError

# The block this config ends with by convention; the seal stanza goes above it.
_SERVICE_REGISTRATION = "service_registration"

# What the overlay says about itself. A generated file that does not say it is
# generated gets hand-edited, and the next render silently drops the edit.
_HEADER = (
    "# Generated by `scripts/sero seal-values`. Do not hand-edit: re-render it.\n"
    "# Layer it after the base values and any environment overlay, last:\n"
    "#   helm upgrade ... -f values-base.yaml -f values-dev.yaml -f seal-values.yaml\n"
)


class _Literal(str):
    """A string to emit as a YAML literal block, not a quoted scalar."""


class _Dumper(yaml.SafeDumper):
    """A dumper with the literal-block representer, registered locally.

    A representer added to ``yaml.SafeDumper`` itself would change how every
    other caller in the process dumps strings, which is not this module's to
    decide.
    """


def _represent_literal(dumper: yaml.Dumper, data: str):
    return dumper.represent_scalar("tag:yaml.org,2002:str", str(data), style="|")


_Dumper.add_representer(_Literal, _represent_literal)


def insert_seal(base_hcl: str, seal_hcl: str) -> str:
    """The server config with the seal stanza in it.

    Trailing whitespace is stripped from every line: a line that ends in a space
    cannot be written as a YAML literal block, so PyYAML would quietly fall back
    to a quoted scalar full of escaped newlines, and the rendered config would
    be unreviewable.
    """
    lines = [line.rstrip() for line in base_hcl.splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    if not lines:
        raise ConfigError("the base server config is empty; there is nothing to extend")

    stanza = [line.rstrip() for line in seal_hcl.strip("\n").splitlines()]

    index = next(
        (i for i, line in enumerate(lines) if line.lstrip().startswith(_SERVICE_REGISTRATION)),
        None,
    )
    if index is None:
        return "\n".join([*lines, "", *stanza]) + "\n"

    before = lines[:index]
    # One blank line between the stanza and whatever precedes it, however the
    # base file was spaced.
    while before and not before[-1]:
        before.pop()
    return "\n".join([*before, "", *stanza, "", *lines[index:]]) + "\n"


def render_seal_values(base_hcl: str, seal: SealConfig, annotations: dict[str, str]) -> str:
    """The Helm values overlay that installs ``seal`` on top of ``base_hcl``.

    Shamir is refused rather than rendered as a no-op overlay: an overlay that
    changed nothing would still replace the server config wholesale, which is a
    lot of risk for no effect, and a deployment asking for it has almost
    certainly not set ``deployment.kms``.
    """
    if seal.provider == SHAMIR or not seal.hcl.strip():
        raise ConfigError(
            "the deployment's kms provider is shamir, which has no seal stanza; "
            "there is no overlay to render"
        )

    server: dict = {"ha": {"raft": {"config": _Literal(insert_seal(base_hcl, seal.hcl))}}}
    if annotations:
        server["serviceAccount"] = {"annotations": dict(annotations)}

    body = yaml.dump({"server": server}, Dumper=_Dumper, sort_keys=False, default_flow_style=False)
    return _HEADER + body
